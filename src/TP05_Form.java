    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        try {

        int maximo = Integer.parseInt(txtMaximo.getText());

        int prioridade1 = Integer.parseInt(txtPrioridade1.getText());
        int prioridade2 = Integer.parseInt(txtPrioridade2.getText());

        if (maximo < 1) {
            JOptionPane.showMessageDialog(this,
                    "O máximo deve ser maior que zero!");
            return;
        }

        if (prioridade1 < 1 || prioridade1 > 10 ||
            prioridade2 < 1 || prioridade2 > 10) {

            JOptionPane.showMessageDialog(this,
                    "As prioridades devem estar entre 1 e 10!");
            return;
        }

        modelo1.clear();
        modelo2.clear();

        lblFim1.setVisible(false);
        lblFim2.setVisible(false);

        Painel1 painel1 = new Painel1(
                maximo, modelo1, lblFim1
        );

        Painel2 painel2 = new Painel2(
                maximo, modelo2, lblFim2
        );

        Thread thread1 = new Thread(painel1);
        Thread thread2 = new Thread(painel2);

        thread1.setPriority(prioridade1);
        thread2.setPriority(prioridade2);

        thread1.start();
        thread2.start();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Digite valores numéricos válidos!");

    }
    }//GEN-LAST:event_btnIniciarActionPerformed

